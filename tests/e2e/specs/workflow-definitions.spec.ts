    const context: WorkflowContext = await (await loadedContext).json()
    expect(context.capabilities).toMatchObject({ read: true, write: true, run: true })
    const protocol = context.protocols.find(protocol => protocol.id === fixtures.analysis.protocol_id)!
    expect(protocol).toBeTruthy()
