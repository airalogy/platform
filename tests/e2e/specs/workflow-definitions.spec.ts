    await page.getByTestId("workflow-preview-save").click()
    const preview: WorkflowSavePreview = await (await previewResponse).json()
    expect(preview.graph.nodes.map(node => node.node_id)).toEqual([secondId, firstId])
    expect(preview.graph.edges).toMatchObject([{ source_node_id: firstId, target_node_id: secondId, condition: null }])
