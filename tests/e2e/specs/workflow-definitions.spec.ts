    await page.getByTestId("analysis-method-preview-publication").click()
    const publicationPreview: WorkflowAnalysisPublicationPreview = await (await publicationPreviewResponse).json()
    expect(publicationPreview.excluded_fields).toEqual(["source_selection", "source_records", "results", "ai_provenance"])
    expect(publicationPreview.publication.recipe).toMatchObject({ numeric_fields: ["measurement"] })
    expect((await listPublications()).items.some((item: { title: string }) => item.title === title)).toBe(false)
    await expect(page.getByTestId("analysis-method-confirm-publication")).toBeDisabled()
